import fs from 'node:fs';
import { getPayload } from 'payload';
import config from '../payload.config';

/**
 * Shows the exact SQL Payload's dev schema push WOULD run against the database
 * in DATABASE_URL — without running any of it.
 *
 * Why it exists: this project has no migration files; the schema reaches the
 * (shared, live) database through the dev push when the app boots. Before a
 * collection change goes anywhere near that database, this prints what the push
 * would do, so a destructive statement (DROP, a data-loss warning) is caught
 * first. For the listings change see docs/LISTINGS-ROLLOUT.md.
 *
 *   PAYLOAD_MIGRATING=true npx payload run scripts/preview-schema-push.ts
 *
 * With RER_SCHEMA_SQL_OUT=<file> it also writes the complete statements, wrapped
 * in BEGIN/COMMIT, so they can be reviewed in full and applied as one transaction
 * (docs/LISTINGS-ROLLOUT.md, option A) instead of through a dev push.
 *
 * Read-only by construction:
 *  - `PAYLOAD_MIGRATING=true` stops Payload pushing at boot (this script refuses
 *    to run without it);
 *  - `disableOnInit` skips `onInit`, whose sequence/amenity "ensure" steps write;
 *  - `pushSchema()` introspects and generates SQL; `apply()` is never called.
 */
async function main() {
  if (process.env.PAYLOAD_MIGRATING !== 'true') {
    console.error('Refusing to run: set PAYLOAD_MIGRATING=true so the boot-time push cannot apply anything.');
    process.exitCode = 1;
    return;
  }

  const host = new URL(process.env.DATABASE_URL ?? 'postgres://unset').host;
  console.log(`Previewing the schema push against: ${host}\n`);

  const payload = await getPayload({ config, disableOnInit: true });
  const { pushSchema } = payload.db.requireDrizzleKit();
  // Payload types the result as { apply, hasDataLoss, warnings }; drizzle-kit also
  // returns the generated statements, which is what this script is for.
  const pushed: unknown = await pushSchema(
    payload.db.schema,
    payload.db.drizzle,
    undefined,
    payload.db.tablesFilter,
  );
  const result = pushed as { hasDataLoss: boolean; warnings: string[]; statementsToExecute: string[] };

  console.log(`hasDataLoss: ${result.hasDataLoss}`);
  console.log(`warnings: ${result.warnings.length ? JSON.stringify(result.warnings) : 'none'}`);
  console.log(`statements: ${result.statementsToExecute.length}`);
  for (const statement of result.statementsToExecute) {
    console.log(`  ${statement.replace(/\s+/g, ' ').slice(0, 200)}`);
  }

  // Index and constraint drops are not data loss, but they are never expected
  // from an additive change and would mean the schema is fighting the database.
  const destructive = result.statementsToExecute.filter((s) =>
    /\bDROP\s+(TABLE|COLUMN|SEQUENCE|TYPE|INDEX|CONSTRAINT)\b|\bTRUNCATE\b/i.test(s),
  );
  console.log(
    destructive.length === 0
      ? '\nNo DROP TABLE / COLUMN / SEQUENCE / TYPE / INDEX / CONSTRAINT or TRUNCATE statements.'
      : `\nDESTRUCTIVE statements present (${destructive.length}) — do not apply:\n${destructive.map((s) => `  ${s}`).join('\n')}`,
  );

  const sqlOut = process.env.RER_SCHEMA_SQL_OUT;
  if (sqlOut) {
    const body = result.statementsToExecute
      .map((s) => s.trim())
      .map((s) => (s.endsWith(';') ? s : `${s};`))
      .join('\n');
    fs.writeFileSync(sqlOut, `-- Generated by scripts/preview-schema-push.ts against ${host}\nBEGIN;\n${body}\nCOMMIT;\n`);
    console.log(`\nFull SQL written to ${sqlOut}`);
  }

  process.exitCode = result.hasDataLoss || destructive.length > 0 ? 1 : 0;

  // Payload keeps the pool open; this is a one-shot script.
  process.exit(process.exitCode);
}

await main();
